#!/usr/bin/env node
// =============================================================================
// scripts/generate-import-report.mjs  — Import report generator
// =============================================================================
// Called by import-lovable.sh. Reads the current repo and emits import-report.md
// with all 6 checks required by the SOW.
// =============================================================================

import { execSync } from 'child_process'
import { existsSync, readFileSync, writeFileSync, readdirSync, statSync } from 'fs'
import { join } from 'path'
import { createHash } from 'crypto'

const HARNESS_VERSION = process.argv[2] ?? '1.0.0'
const IMPORT_DATE = new Date().toISOString()

function run(cmd) {
  try {
    return execSync(cmd, { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }).trim()
  } catch (e) {
    return (e.stdout ?? '') + (e.stderr ?? '')
  }
}

function grepRecursive(pattern, dirs, flags = 'rEn') {
  const existing = dirs.filter((d) => existsSync(d))
  if (existing.length === 0) return ''
  try {
    return execSync(`grep -${flags} "${pattern}" ${existing.join(' ')}`, {
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'pipe'],
    }).trim()
  } catch {
    return ''
  }
}

// ─── Check 1: Float currency math ────────────────────────────────────────────
const floatHits = grepRecursive('toFixed\\s*\\(', ['src'])
const floatCount = floatHits ? floatHits.split('\n').filter(Boolean).length : 0

// ─── Check 2: data-testid coverage ───────────────────────────────────────────
const allInteractive = grepRecursive('<(button|input|select|textarea)', ['src'])
const missingTestId = allInteractive
  ? allInteractive
      .split('\n')
      .filter((l) => l && !l.includes('data-testid'))
  : []
const missingCount = missingTestId.length

// ─── Check 3: TypeScript errors ──────────────────────────────────────────────
const tscOutput = run('npx tsc --noEmit 2>&1')
const tscErrors = tscOutput
  .split('\n')
  .filter((l) => l.includes('error TS'))
const tscErrorCount = tscErrors.length

// ─── Check 4: Lint errors ─────────────────────────────────────────────────────
const lintOutput = run('npx @biomejs/biome check src/ 2>&1')
const lintErrorCount = (lintOutput.match(/error/gi) ?? []).length

// ─── Check 5: Banned patterns ─────────────────────────────────────────────────
const BANNED_PATTERN =
  '@ts-ignore|@ts-expect-error|as any|biome-ignore|test\\.skip|test\\.only|xit\\(|describe\\.skip'
const bannedHits = grepRecursive(BANNED_PATTERN, ['src', 'e2e'])
const bannedCount = bannedHits ? bannedHits.split('\n').filter(Boolean).length : 0

// ─── Check 6: Off-platform dependencies ──────────────────────────────────────
const PLATFORM_LIST = new Set([
  'react',
  'react-dom',
  'vite',
  'typescript',
  '@vitejs/plugin-react',
  '@biomejs/biome',
  '@playwright/test',
  '@types/react',
  '@types/react-dom',
])

let offPlatform = []
try {
  const pkg = JSON.parse(readFileSync('package.json', 'utf8'))
  const all = { ...(pkg.dependencies ?? {}), ...(pkg.devDependencies ?? {}) }
  offPlatform = Object.keys(all).filter((k) => !PLATFORM_LIST.has(k))
} catch {}

// ─── Build report ─────────────────────────────────────────────────────────────
const lines = []

lines.push('# Import Report')
lines.push('')
lines.push(`Generated by \`scripts/import-lovable.sh\` on ${IMPORT_DATE}`)
lines.push(`Harness version: ${HARNESS_VERSION}`)
lines.push('')
lines.push('---')
lines.push('')

// Check 1
lines.push('## Check 1 — Float Currency Math (toFixed)')
lines.push('')
lines.push(`**Count**: ${floatCount} occurrence(s)`)
lines.push('')
lines.push('Generators default to float math with `.toFixed()`. Harness standard is integer cents.')
if (floatCount > 0) {
  lines.push('```')
  lines.push(floatHits)
  lines.push('```')
} else {
  lines.push('_No float currency math detected._')
}
lines.push('')
lines.push('---')
lines.push('')

// Check 2
lines.push('## Check 2 — Missing data-testid on Interactive Elements')
lines.push('')
lines.push(`**Count**: ${missingCount} interactive element(s) without \`data-testid\``)
lines.push('')
lines.push('Every element the Playwright tests touch needs a `data-testid` attribute.')
if (missingCount === 0) {
  lines.push('_All interactive elements have data-testid._')
} else {
  lines.push('Elements missing data-testid:')
  lines.push('```')
  missingTestId.slice(0, 20).forEach((l) => lines.push(l))
  lines.push('```')
}
lines.push('')
lines.push('---')
lines.push('')

// Check 3
lines.push('## Check 3 — TypeScript Error Baseline')
lines.push('')
lines.push(`**Error count at import**: ${tscErrorCount}`)
lines.push('')
lines.push(
  'These errors are inherited debt, not introduced by Dyad. Any new errors in the loop are regressions.'
)
if (tscErrorCount > 0) {
  lines.push('```')
  tscErrors.slice(0, 30).forEach((l) => lines.push(l))
  lines.push('```')
} else {
  lines.push('_Clean typecheck at import._')
}
lines.push('')
lines.push('---')
lines.push('')

// Check 4
lines.push('## Check 4 — Lint Error Baseline')
lines.push('')
lines.push(`**Error count at import**: ${lintErrorCount}`)
lines.push('')
if (lintErrorCount === 0) {
  lines.push('_Clean lint at import._')
} else {
  lines.push('```')
  lintOutput
    .split('\n')
    .slice(0, 20)
    .forEach((l) => lines.push(l))
  lines.push('```')
}
lines.push('')
lines.push('---')
lines.push('')

// Check 5
lines.push('## Check 5 — Banned Patterns Already Present')
lines.push('')
lines.push(`**Count**: ${bannedCount} banned pattern(s) in source`)
lines.push('')
lines.push(`Pattern: \`${BANNED_PATTERN}\``)
lines.push('')
if (bannedCount === 0) {
  lines.push('_No banned patterns found._')
} else {
  lines.push('```')
  lines.push(bannedHits)
  lines.push('```')
}
lines.push('')
lines.push('---')
lines.push('')

// Check 6
lines.push('## Check 6 — Off-Platform Dependencies')
lines.push('')
lines.push(`**Count**: ${offPlatform.length} package(s) not on the platform list`)
lines.push('')
lines.push(`Platform list: ${[...PLATFORM_LIST].join(', ')}`)
lines.push('')
if (offPlatform.length === 0) {
  lines.push('_All dependencies are on the platform list._')
} else {
  lines.push('Packages requiring review:')
  lines.push('```')
  offPlatform.forEach((p) => lines.push(p))
  lines.push('```')
}
lines.push('')
lines.push('---')
lines.push('')
lines.push('_End of import report._')
lines.push('')

writeFileSync('import-report.md', lines.join('\n'))
console.log('[import-report] Written to import-report.md')
console.log(
  `[import-report] Summary: float=${floatCount} testid_missing=${missingCount} tsc_errors=${tscErrorCount} lint_errors=${lintErrorCount} banned=${bannedCount} off_platform=${offPlatform.length}`
)
